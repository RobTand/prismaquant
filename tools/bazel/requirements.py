#!/usr/bin/env python3
"""Export pip.parse's hashed requirements from the frozen project lock.

The hosted gate installs, on every shard (.github/workflows/gate.yml):
the pinned Tessera commit (tools/resolve_tessera_dev_pin.py) with --no-deps,
torch from the PyTorch CPU index, and `pip install -c .github/ci-constraints.txt
-e '.[test]'`. The frozen uv export selects the test extra, then filters
its markers for each Linux architecture. It generates:

- tools/bazel/requirements_linux_x86_64.txt and ..._aarch64.txt, for pip.parse;
- tools/bazel/pip_modules.json, each importable top-level name and the
  distribution that provides it, so tools/bazel/build_files.py gives every
  library the @pq_pip packages it really imports.

--check needs no network: each export must name the current sources' sha256
and pin every package the constraints pin, and Tessera at the pinned commit.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import tomllib
import urllib.request

from packaging.markers import default_environment
from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[2]
# PrismaQuant's one digest owner, as tools/ci/gate_select.py imports it.
sys.path.insert(0, str(ROOT))
from prismaquant.digests import bytes_sha256hex  # noqa: E402

SOURCES = ('pyproject.toml', 'uv.lock', '.github/ci-constraints.txt', 'prismaquant/tessera_runtime_contract.py')
PLATFORMS = {'linux_x86_64': 'x86_64-manylinux_2_28', 'linux_aarch64': 'aarch64-manylinux_2_28'}
EXPORT = 'tools/bazel/requirements_{}.txt'
MODULES = 'tools/bazel/pip_modules.json'
FIX = 'python3 tools/bazel/requirements.py'
PYTHON = '3.12'
TORCH_INDEX = 'https://download.pytorch.org/whl/cpu'
TESSERA = 'https://github.com/RobTand/tessera/archive/{}.tar.gz'
PIN = re.compile(r'^([A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[^\]]*\])?\s*(?:==\s*([^\s;\\]+)|@\s*(\S+))', re.MULTILINE)


def normal(name):
    return re.sub(r'[-_.]+', '-', name).lower()


def pins(text):
    """{distribution: version or URL} for each `name==version` or `name @ url` line."""
    return {normal(name): version or url for name, version, url in PIN.findall(text)}


def _literal_pin(root):
    """The Tessera commit, read the way tools/resolve_tessera_dev_pin.py reads it."""
    output = subprocess.run([sys.executable, '-s', str(root / 'tools/resolve_tessera_dev_pin.py')], cwd=root,
                            capture_output=True, text=True, check=True).stdout.strip()
    if not re.fullmatch(r'[0-9a-f]{40}', output):
        raise SystemExit(f'tools/resolve_tessera_dev_pin.py printed {output!r}, not a commit')
    return output


def source_digest(root):
    return bytes_sha256hex(b''.join(name.encode() + b'\0' + (root / name).read_bytes() + b'\0' for name in SOURCES))


def header(root, platform):
    return (f'# Generated by {FIX} from {", ".join(SOURCES)} for {platform}; do not edit.\n'
            f'# source-sha256: {source_digest(root)}\n# uv: 0.10.10 frozen test extra\n'
            f'# torch: {TORCH_INDEX} (MODULE.bazel experimental_index_url_overrides)\n')


def export_blocks(text):
    """Read uv's requirement headers and their hash continuation lines."""
    blocks, current = [], []
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        if not line[0].isspace():
            if current:
                blocks.append(current)
            current = [line.rstrip().removesuffix('\\').strip()]
        elif line.strip().startswith('--hash='):
            current.append(line.strip().removesuffix('\\').strip())
    if current:
        blocks.append(current)
    return blocks


def hashed_requirement(requirement, hashes):
    if not hashes:
        raise RuntimeError(f'lock export has no hashes for {requirement}')
    continuation = " " + "\\" + "\n"
    return continuation.join([str(requirement)] + ['    ' + digest for digest in hashes])


def problems(root, platform, export):
    """Why one export no longer matches the sources; empty when it does."""
    found = []
    name = EXPORT.format(platform)
    if not export.startswith(header(root, platform)):
        found.append(f'{name} was not generated from the current {", ".join(SOURCES)}')
    exported = pins(export)
    for package, version in sorted(pins((root / '.github/ci-constraints.txt').read_text()).items()):
        if exported.get(package) != version:
            found.append(f'.github/ci-constraints.txt pins {package}=={version}; {name} has {exported.get(package)}')
    tessera = TESSERA.format(_literal_pin(root))
    if exported.get('tessera-quant') != tessera:
        found.append(f'{name} has tessera-quant {exported.get("tessera-quant")}, not {tessera}')
    if not str(exported.get('torch', '')).endswith('+cpu'):
        found.append(f'{name} has torch {exported.get("torch")}, not a +cpu build')
    return found


def compile_for(root, platform, temporary):
    """Filter the frozen universal export for one Linux execution platform."""
    result = subprocess.run(['uv', 'export', '--frozen', '--extra', 'test',
                             '--no-default-groups', '--no-emit-project', '--format', 'requirements.txt'],
                            cwd=root, capture_output=True, text=True, check=True)
    environment = dict(default_environment(), os_name='posix', sys_platform='linux',
                       platform_system='Linux', platform_machine=platform.removeprefix('linux_'),
                       python_version=PYTHON, python_full_version=PYTHON + '.0')
    blocks = []
    for block in export_blocks(result.stdout):
        requirement = Requirement(block[0])
        if requirement.marker and not requirement.marker.evaluate(environment):
            continue
        requirement.marker = None
        hashes = block[1:]
        blocks.append(hashed_requirement(requirement, hashes))
    # Hosted Tessera is deliberately installed separately with --no-deps.
    # Preserve that exact immutable archive, outside the project's uv lock.
    tessera = TESSERA.format(_literal_pin(root))
    old = (root / EXPORT.format(platform)).read_text()
    existing = next((block for block in export_blocks(old)
                     if normal(Requirement(block[0]).name) == 'tessera-quant'
                     and Requirement(block[0]).url == tessera), None)
    if existing is None:
        with urllib.request.urlopen(tessera, timeout=120) as response:
            digest = bytes_sha256hex(response.read())
        existing = ['tessera-quant @ ' + tessera, '--hash=sha256:' + digest]
    blocks.append(hashed_requirement(Requirement(existing[0]), existing[1:]))
    return '\n\n'.join(sorted(blocks)) + '\n'


def top_level_modules(export, temporary):
    """{import name: distribution} from the exported wheels' own RECORD files."""
    target = Path(temporary, 'site')
    requirements = Path(temporary, 'install.txt')
    requirements.write_text(export)
    subprocess.run(['uv', 'pip', 'install', '--target', str(target), '--no-deps', '--require-hashes',
                    '--python', PYTHON, '--python-platform', PLATFORMS['linux_x86_64'],
                    '--extra-index-url', TORCH_INDEX, '--index-strategy', 'unsafe-best-match',
                    '--quiet', '-r', str(requirements)], check=True)
    found = {}
    for info in sorted(target.glob('*.dist-info')):
        distribution = normal(info.name.removesuffix('.dist-info').rsplit('-', 1)[0])
        names = set()
        for line in (info / 'RECORD').read_text().splitlines():
            first = line.split(',', 1)[0].split('/', 1)[0].removesuffix('.py')
            if not first.endswith(('.dist-info', '.data')) and first.isidentifier() and first not in ('__pycache__', 'bin'):
                names.add(first)
        for name in names:
            found.setdefault(name, set()).add(distribution)
    return {name: sorted(distributions) for name, distributions in sorted(found.items())}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n', 1)[0])
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args(argv)
    if args.check:
        found = []
        for platform in PLATFORMS:
            found += problems(args.root, platform, (args.root / EXPORT.format(platform)).read_text())
        if found:
            sys.exit('Bazel requirements drifted:\n' + '\n'.join(found) + f'\nFix: {FIX}')
        return 0
    with tempfile.TemporaryDirectory() as temporary:
        exports = {}
        for platform in PLATFORMS:
            exports[platform] = header(args.root, platform) + compile_for(args.root, platform, temporary)
            (args.root / EXPORT.format(platform)).write_text(exports[platform])
        modules = top_level_modules(exports['linux_x86_64'], temporary)
    (args.root / MODULES).write_text(json.dumps(modules, indent=1) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
